# =========================================================
# IMPORTS
# =========================================================

import re
import string
import pandas as pd

from nltk.corpus import stopwords
from nltk.stem import WordNetLemmatizer


# =========================================================
# NLP TOOLS
# =========================================================

stop_words = set(
    stopwords.words('english')
)

lemmatizer = WordNetLemmatizer()


# =========================================================
# TEXT CLEANING
# =========================================================

def clean_text(text):

    # -----------------------------------------------------
    # HANDLE MISSING VALUES
    # -----------------------------------------------------

    if pd.isna(text):
        return ""

    # -----------------------------------------------------
    # CONVERT TO LOWERCASE
    # -----------------------------------------------------

    text = text.lower()

    # -----------------------------------------------------
    # REMOVE URLS
    # -----------------------------------------------------

    text = re.sub(
        r'http\S+|www\S+',
        '',
        text
    )

    # -----------------------------------------------------
    # REMOVE HTML TAGS
    # -----------------------------------------------------

    text = re.sub(
        r'<.*?>',
        '',
        text
    )

    # -----------------------------------------------------
    # REMOVE PUNCTUATION
    # -----------------------------------------------------

    text = text.translate(
        str.maketrans(
            '',
            '',
            string.punctuation
        )
    )

    # -----------------------------------------------------
    # REMOVE NUMBERS
    # -----------------------------------------------------

    text = re.sub(
        r'\d+',
        '',
        text
    )

    # -----------------------------------------------------
    # REMOVE EXTRA WHITESPACES
    # -----------------------------------------------------

    text = re.sub(
        r'\s+',
        ' ',
        text
    ).strip()

    return text


# =========================================================
# FULL NLP PREPROCESSING PIPELINE
# =========================================================

def preprocess_text(text):

    # -----------------------------------------------------
    # BASIC CLEANING
    # -----------------------------------------------------

    text = clean_text(text)

    # -----------------------------------------------------
    # TOKENIZATION
    # -----------------------------------------------------

    tokens = re.findall(
        r'\w+',
        text
    )

    # -----------------------------------------------------
    # STOPWORD REMOVAL
    # -----------------------------------------------------

    tokens = [
        word
        for word in tokens
        if word not in stop_words
    ]

    # -----------------------------------------------------
    # LEMMATIZATION
    # -----------------------------------------------------

    tokens = [
        lemmatizer.lemmatize(word)
        for word in tokens
    ]

    # -----------------------------------------------------
    # JOIN TOKENS
    # -----------------------------------------------------

    processed_text = " ".join(tokens)

    return processed_text